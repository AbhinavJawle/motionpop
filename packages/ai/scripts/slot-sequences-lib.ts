// Spec 39 task 3: pulls the `## Shot sequence…` section out of each `skills/*.md` (top level
// only). Used by build-slot-sequences.ts to write the bundled map, and by its sync test.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** Longest shot sequence kept per skill (the on-device prompt is small). */
export const SEQUENCE_MAX_CHARS = 1200;

/** The skill's `id` from its front matter, or null. */
export function skillIdOf(md: string): string | null {
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md)?.[1] ?? '';
  const m = /^id:\s*(.+?)\s*$/m.exec(block);
  return m?.[1] ?? null;
}

/**
 * The body of the `## Shot sequence…` section, up to the next `## ` heading, trimmed to
 * `SEQUENCE_MAX_CHARS` (cut at a line end so no bullet is split). '' when there is no section.
 */
export function extractShotSequence(md: string): string {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const start = lines.findIndex((l) => /^##\s+Shot sequence/i.test(l));
  if (start < 0) return '';
  const body: string[] = [];
  for (const line of lines.slice(start + 1)) {
    if (/^##\s/.test(line)) break;
    body.push(line);
  }
  const text = body.join('\n').trim();
  if (text.length <= SEQUENCE_MAX_CHARS) return text;
  const cut = text.slice(0, SEQUENCE_MAX_CHARS);
  const lastBreak = cut.lastIndexOf('\n');
  return (lastBreak > 0 ? cut.slice(0, lastBreak) : cut).trimEnd();
}

/** id → shot sequence for every `*.md` directly inside `skillsDir`, ordered by file name. */
export function buildSlotSequences(skillsDir: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const file of readdirSync(skillsDir)
    .filter((f) => f.endsWith('.md'))
    .sort()) {
    const md = readFileSync(join(skillsDir, file), 'utf8');
    const id = skillIdOf(md);
    if (!id) throw new Error(`skills/${file}: no id in the front matter`);
    if (id in out) throw new Error(`skills/${file}: duplicate skill id ${id}`);
    out[id] = extractShotSequence(md);
  }
  return out;
}

/** The TypeScript source of `slot-sequences.ts` for a map (not yet formatted). */
export function renderSlotSequencesModule(map: Readonly<Record<string, string>>): string {
  const entries = Object.entries(map)
    .map(([id, text]) => `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`)
    .join('\n');
  return `// GENERATED by packages/ai/scripts/build-slot-sequences.ts from skills/*.md. Do not edit.
// Run \`pnpm --filter @motionpop/ai skills:build\` after changing a skill; slot-sequences.test.ts
// fails when this file is out of date.

export const SLOT_SEQUENCES: Readonly<Record<string, string>> = {
${entries}
};

/** The "Shot sequence" text of a voiceover skill, or '' for an unknown id. */
export function shotSequenceOf(skillId: string): string {
  return Object.hasOwn(SLOT_SEQUENCES, skillId) ? (SLOT_SEQUENCES[skillId] ?? '') : '';
}
`;
}
