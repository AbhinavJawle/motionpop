// (see `normalizePlaceKey`): lowercase ASCII, single spaces, no dots.

/**
 * Normalises one token for place matching: lowercase, accents removed, curly apostrophes
 * straightened, edge punctuation stripped, dotted abbreviations collapsed ("U.S." → "us").
 */
export function normalizePlaceKey(token: string): string {
  const s = token
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[’‘]/g, "'")
    .replace(/^[^a-z0-9]+|[^a-z0-9]+$/g, '');
  return /^(?:[a-z]\.)+[a-z]$/.test(s) ? s.replace(/\./g, '') : s;
}

