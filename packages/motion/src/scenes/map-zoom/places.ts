/** Display names for keys that read badly title-cased. */
const DISPLAY: Record<string, string> = {
  us: 'United States',
  usa: 'United States',
  uk: 'United Kingdom',
  uae: 'United Arab Emirates',
  drc: 'DR Congo',
};

const titleCase = (key: string) => key.replace(/\b[a-z]/g, (c) => c.toUpperCase());

/**
 * The map target for a spoken place name, or null when we have no shape or point for it.
 * `countryNames` is the set of Natural Earth names available (from the topology).
 */
export function resolvePlace(name: string, countryNames: ReadonlySet<string>): PlaceTarget | null {
  const key = placeKey(name);
  if (!key) return null;
  const display = DISPLAY[key] ?? titleCase(key);
  const region = REGIONS[key];
  if (region) return { kind: 'region', name: display, box: region };
  const point = POINTS[key];
  if (point) return { kind: 'point', name: display, lon: point[0], lat: point[1] };
  const alias = COUNTRY_ALIASES[key];
  if (alias && countryNames.has(alias)) return { kind: 'country', name: display, neName: alias };
  for (const ne of countryNames) {
    if (placeKey(ne) === key) return { kind: 'country', name: ne, neName: ne };
  }
  return null;
}
