/**
 * Place names to map targets for the map-zoom scene. Countries resolve to Natural Earth admin-0
 * shapes (public domain, via world-atlas 110m); cities, micro-states and a few named areas to a
 * point; continents and regions to a lon/lat box. Hand-written, no network.
 */

export type PlaceTarget =
  | { kind: 'country'; name: string; neName: string }
  | { kind: 'point'; name: string; lon: number; lat: number }
  | { kind: 'region'; name: string; box: [number, number, number, number] };

/** Lowercase ASCII, accents removed, punctuation dropped, single spaces ("Côte d'Ivoire" → "cote divoire"). */
export function placeKey(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[’'‘.]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/^the /, '');
}

