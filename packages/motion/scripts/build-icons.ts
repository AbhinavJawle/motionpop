// Generates src/film/icons.generated.ts: a curated set of Lucide icons (ISC licence, see
// docs/third-party.md) as plain shape lists, for the film kit's `mp.icon(name)`. Run once when
// the list changes: node scripts/build-icons.ts. Reads the icon shapes from the lucide-react
// package the web app already depends on; nothing from React is bundled.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES =
  `ship sailboat anchor container truck plane plane-takeoff rocket car bus train-front bike fuel
globe map map-pin compass mountain building building-2 factory house landmark warehouse store school hospital tent trees tree-pine waves
coins banknote wallet piggy-bank credit-card dollar-sign euro receipt trending-up trending-down chart-column chart-line chart-pie percent scale
user users baby person-standing hand handshake heart brain eye ear footprints graduation-cap crown
cpu smartphone laptop monitor server database wifi cloud satellite satellite-dish radio battery-full plug zap bot code lock key shield bug
atom flask-conical microscope dna thermometer magnet telescope pill syringe stethoscope
sun moon star cloud-rain snowflake flame droplet leaf sprout wind fish bird
clock calendar hourglass timer book-open newspaper mail phone megaphone lightbulb wrench hammer package box shopping-cart gift trophy flag target bell camera music mic
wheat apple utensils coffee
arrow-right arrow-up-right check x plus minus triangle-alert ban info infinity equal
swords bomb gavel vote oil-barrel pickaxe drill construction tractor cog`
    .split(/\s+/)
    .filter(Boolean);

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../../apps/web/node_modules/lucide-react/dist/esm/icons');
const out: Record<string, [string, Record<string, string>][]> = {};
const missing: string[] = [];
for (const name of NAMES) {
  const file = join(dir, `${name}.mjs`);
  if (!existsSync(file)) {
    missing.push(name);
    continue;
  }
  const src = readFileSync(file, 'utf8');
  const start = src.indexOf('node: [');
  if (start < 0) {
    missing.push(name);
    continue;
  }
  // The array literal after `node:`, found by matching brackets.
  let depth = 0;
  let end = -1;
  for (let i = start + 6; i < src.length; i++) {
    if (src[i] === '[') depth++;
    else if (src[i] === ']' && --depth === 0) {
      end = i + 1;
      break;
    }
  }
  if (end < 0) {
    missing.push(name);
    continue;
  }
  // The package's own data literal (arrays of [tag, attributes]); evaluated at build time only.
  const node = new Function(`return ${src.slice(start + 6, end)};`)() as [
    string,
    Record<string, string>,
  ][];
  out[name] = node.map(([tag, attrs]) => {
    const rest = { ...attrs };
    delete rest['key'];
    return [tag, rest];
  });
}
const body = `// Generated by scripts/build-icons.ts from lucide-react (ISC). Do not edit by hand.
export const KIT_ICONS: Readonly<Record<string, readonly (readonly [string, Readonly<Record<string, string>>])[]>> = ${JSON.stringify(out)};
export const KIT_ICON_NAMES: readonly string[] = ${JSON.stringify(Object.keys(out))};
`;
writeFileSync(join(here, '../src/film/icons.generated.ts'), body);
console.log(
  `icons: ${Object.keys(out).length} written${missing.length ? `, missing: ${missing.join(' ')}` : ''}`,
);
