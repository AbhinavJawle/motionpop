// Synchronous SHA-256 and a stable JSON text, for cache keys and render identities (spec 13b R2,
// R4). Pure JavaScript, so it works in every browser context (`crypto.subtle` is missing on plain
// http pages) and on the server alike. Checked against the FIPS 180-4 vectors in hash.test.ts.

